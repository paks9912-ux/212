#!/usr/bin/env node
/* Персонализация первого касания.
   crm.csv -> sales/outreach/<компания>.md  (сообщение под конкретное заведение)
           -> menu/shops/lead-<id>.json     (заготовка демо, чтобы собрать сайт за минуту)
   Массовых безликих рассылок не делаем: у каждого лида свой текст. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
/* Живое демо — то, что открывает заведение. Меняется в одном месте. */
const DEMO_URL = 'https://claude.ai/code/artifact/d34e5c3e-43d5-4868-9534-93755a344f74';

function readCsv(f) {
  const txt = fs.readFileSync(f, 'utf8').trim();
  const rows = []; let cur = [], val = '', q = false;
  for (let i = 0; i < txt.length; i++) {
    const c = txt[i];
    if (q) { if (c === '"' && txt[i + 1] === '"') { val += '"'; i++; } else if (c === '"') q = false; else val += c; }
    else if (c === '"') q = true;
    else if (c === ',') { cur.push(val); val = ''; }
    else if (c === '\n') { cur.push(val); rows.push(cur); cur = []; val = ''; }
    else if (c !== '\r') val += c;
  }
  if (val || cur.length) { cur.push(val); rows.push(cur); }
  const head = rows.shift();
  return rows.filter(r => r.length > 1).map(r => Object.fromEntries(head.map((h, i) => [h, (r[i] || '').trim()])));
}

const money = n => Number(n).toLocaleString('ru-RU').replace(/ /g, ' ');
const slug = s => s.toLowerCase().replace(/[^a-z0-9а-яё]+/gi, '-').replace(/^-|-$/g, '');

/* Крючок под сегмент — то, что делает сообщение «про них», а не шаблоном */
const HOOK = {
  'Суши': 'у суши почти всегда большое меню и сеты — гостю тяжело выбирать по картинке в постах',
  'Пицца': 'в пицце много позиций и размеров — по картинке в ленте это выбирать неудобно',
  'Бургеры': 'по бургерам гости часто спрашивают состав и добавки — на сайте это видно сразу',
  'Фастфуд': 'у фастфуда заказы частые и мелкие — считать каждый вручную дороже всего',
  'Кондитерская': 'торты почти всегда заказывают через директ с долгой перепиской',
  'Кофейня': 'в зале удобнее QR-меню: гость сканирует табличку и видит актуальные цены',
  'Кафе': 'меню в зале и меню на доставку удобно держать в одном месте',
  'Ресторан': 'печатное меню устаревает при каждом изменении цен',
  'Обеды': 'комплексные обеды заказывают каждый день — тут ручной подсчёт особенно изматывает'
};

function message(l) {
  const nightly = /0[0-5]:00|до 03:00|до 05:00|02:00|24\/7/.test(l['Заметка'] + l['Проблема (гипотеза)']);
  const qr = l['Оффер'] === 'QR-меню';
  const hook = HOOK[l['Сегмент']] || 'меню в картинках неудобно смотреть с телефона';
  const who = l['Компания'];
  const price = money(l['Чек (сум)']);

  if (qr) {
    return `Здравствуйте! Пишу по «${who}».

Заметил, что меню у вас в зале печатное, а онлайн его нет.
Сделал QR-меню: гость сканирует табличку на столе и открывает меню на телефоне — с ценами, весом и составом. Цены меняются за минуту, перепечатывать ничего не нужно.

Собрал для вас пример, откройте с телефона: ${DEMO_URL}
Блюда взял примерные — поставлю ваши.

Сделал бесплатно, чтобы показать. Если подойдёт — QR-меню под ключ ${price} сум, включая таблички на столы.
Если не актуально — скажите, больше не побеспокою.`;
  }

  return `Здравствуйте! Пишу по «${who}».

Вижу, заказы вы принимаете в директе${l['Телефон'] ? ' и по телефону' : ''}. ${hook.charAt(0).toUpperCase() + hook.slice(1)}.

Собрал для вас сайт-меню: гость сам выбирает блюда, а вам в WhatsApp падает готовый заказ — состав, адрес, сумма. Считать вручную не нужно.${nightly ? '\nОсобенно выручает ночью, когда оператор один.' : ''}

Откройте с телефона: ${DEMO_URL}
Цены и позиции пока примерные — поставлю ваши.

Сделал бесплатно, чтобы показать. Если понравится — запуск за сутки, ${price} сум, комиссии с заказов нет.
Если не актуально — просто скажите, больше не пишу.`;
}

const leads = readCsv(path.join(ROOT, 'sales', 'crm.csv'))
  .filter(l => l['Приоритет'] === 'A' || l['Приоритет'] === 'B');

const outDir = path.join(ROOT, 'sales', 'outreach');
fs.mkdirSync(outDir, { recursive: true });
const index = [];

for (const l of leads) {
  const id = slug(l['Компания']);
  const msg = message(l);
  const ch = [];
  if (l['Instagram']) ch.push('Instagram Direct: ' + l['Instagram']);
  if (l['Телефон']) ch.push('WhatsApp/звонок: ' + l['Телефон']);

  fs.writeFileSync(path.join(outDir, id + '.md'),
    `# ${l['Компания']}\n\n` +
    `- Приоритет: **${l['Приоритет']}** · Сегмент: ${l['Сегмент']}\n` +
    `- Куда писать: ${ch.join(' · ') || 'контакт не найден — уточнить'}\n` +
    `- Оффер: **${l['Оффер']}** — ${money(l['Чек (сум)'])} сум\n` +
    `- Гипотеза боли: ${l['Проблема (гипотеза)']}\n` +
    (l['Заметка'] ? `- Заметка: ${l['Заметка']}\n` : '') +
    `\n> Перед отправкой: открыть профиль, убедиться, что заведение работает и\n` +
    `> контакт актуален. Данные собраны из публичного поиска и могут устареть.\n` +
    `\n---\n\n## Сообщение\n\n${msg}\n`);

  /* заготовка демо: остаётся вставить меню в конструктор */
  fs.writeFileSync(path.join(ROOT, 'menu', 'shops', 'lead-' + id + '.json'), JSON.stringify({
    id: 'lead-' + id, name: l['Компания'],
    tagline: l['Сегмент'] + ' · доставка по Ташкенту',
    emoji: { 'Суши': '🍣', 'Пицца': '🍕', 'Бургеры': '🍔', 'Фастфуд': '🌯', 'Кондитерская': '🎂', 'Кофейня': '☕', 'Кафе': '🍽', 'Ресторан': '🍽', 'Обеды': '🍲' }[l['Сегмент']] || '🍽',
    accent: '#ff5a3c', currency: 'сум',
    phone: l['Телефон'], whatsapp: (l['Телефон'] || '').replace(/\D/g, ''),
    instagram: (l['Instagram'] || '').replace(/^@/, ''),
    hours: { from: '10:00', to: '23:00' },
    delivery: { fee: 15000, freeFrom: 200000, minOrder: 0, time: '40–60 мин', zone: 'Ташкент' },
    categories: [{ name: 'Меню', items: [{ id: 'i0_0', name: 'Позиция 1 — заменить', price: 50000 }] }]
  }, null, 2));

  index.push(`| ${l['Приоритет']} | ${l['Компания']} | ${l['Сегмент']} | ${ch[0] || '—'} | ${money(l['Чек (сум)'])} | [текст](${id}.md) |`);
}

fs.writeFileSync(path.join(outDir, 'README.md'),
  `# Персональные сообщения\n\nСгенерировано: ${leads.length}. Порядок работы — сверху вниз, ` +
  `по 15–20 сообщений в день.\n\n` +
  `| Приоритет | Заведение | Сегмент | Куда писать | Чек, сум | Текст |\n|---|---|---|---|---|---|\n` +
  index.join('\n') + '\n');

console.log('Сообщений сгенерировано: ' + leads.length);
console.log('Заготовок демо: ' + leads.length);
